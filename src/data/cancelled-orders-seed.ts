export function getPopulatedDemoOrders(): CancelledOrderRecord[] {
  // Executa o motor analítico em lote sobre os registros de demonstração
  const results: CancelledOrderRecord[] = []

  for (const raw of rawDemoOrders) {
    const aiAnalysis = CancelledOrdersAIEngine.analyzeOrder(
      raw,
      rawDemoOrders as CancelledOrderRecord[],
    )

    const fullRecord: CancelledOrderRecord = {
      ...(raw as CancelledOrderRecord),
      has_ai_inconsistency: aiAnalysis.hasInconsistency,
      ai_verification_status: aiAnalysis.verificationStatus,
      ai_probable_cause: aiAnalysis.probableCause,
      ai_suggested_responsibility: aiAnalysis.suggestedResponsibility,
      ai_confidence_level: aiAnalysis.confidenceLevel,
      ai_avoidable_status: aiAnalysis.avoidableStatus,
      ai_priority: aiAnalysis.priority,
      ai_action_suggested: aiAnalysis.actionSuggested,
      ai_analysis_payload: aiAnalysis,
    }

    results.push(fullRecord)
  }

  return results
}
